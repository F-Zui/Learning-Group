SEC.append(C(r'''#include <bits/stdc++.h>
using namespace std;

const int MAXN = 100005;
int n, m;
vector<int> g[MAXN];          // g[u]：u 引用的所有文献
bool vis[MAXN];               // 判重：每个点最多真正访问一次

// 按顺序输出，编号之间一个空格，行末只有换行
void printOrder(const vector<int> &ord) {
    for (int i = 0; i < (int)ord.size(); ++i) {
        if (i) putchar(' ');
        printf("%d", ord[i]);
    }
    putchar('\n');
}

int main() {
    scanf("%d%d", &n, &m);
    for (int i = 0; i < m; ++i) {
        int x, y;
        scanf("%d%d", &x, &y);
        g[x].push_back(y);              // 有向边 X -> Y，只加一条
    }
    // 题目要求小编号优先；邻接表里是读入顺序，必须自己排
    for (int i = 1; i <= n; ++i) sort(g[i].begin(), g[i].end());

    // ---------------- DFS：显式栈，避免 1e5 深度爆栈 ----------------
    vector<int> ord, st;
    st.push_back(1);
    while (!st.empty()) {
        int u = st.back(); st.pop_back();
        if (vis[u]) continue;           // 可能被多个点重复压栈，只处理第一次
        vis[u] = 1;
        ord.push_back(u);
        // 倒序压栈：编号最小的出点最后压，弹出时最先访问，与递归 DFS 一致
        for (int i = (int)g[u].size() - 1; i >= 0; --i) st.push_back(g[u][i]);
    }
    printOrder(ord);

    // ---------------- BFS：队列，入队即标记 ----------------
    memset(vis, 0, sizeof vis);         // 两遍遍历之间必须清空
    ord.clear();
    queue<int> q;
    q.push(1); vis[1] = 1;
    while (!q.empty()) {
        int u = q.front(); q.pop();
        ord.push_back(u);
        for (int v : g[u]) {
            if (vis[v]) continue;
            vis[v] = 1;                 // 入队立刻标记，否则同一点会重复进队
            q.push(v);
        }
    }
    printOrder(ord);
    return 0;
}''', "完整代码 · 邻接表 + 显式栈 DFS + BFS"))

