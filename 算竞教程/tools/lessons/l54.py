SEC.append(C(r'''#include <bits/stdc++.h>
using namespace std;

const int N = 10005;
const int M = 100005;

int head[N], nxt[M << 1], to[M << 1], ecnt;
int col[N];                             // -1 未染色，0 / 1 两种颜色

void addEdge(int u, int v) {
    to[++ecnt] = v; nxt[ecnt] = head[u]; head[u] = ecnt;
}

// 对 s 所在连通块染色；能二染色返回 true
bool paint(int s) {
    queue<int> q;
    q.push(s);
    col[s] = 0;
    while (!q.empty()) {
        int u = q.front(); q.pop();
        for (int e = head[u]; e; e = nxt[e]) {
            int v = to[e];
            if (col[v] == -1) {                  // 没染过：染成相反色
                col[v] = col[u] ^ 1;
                q.push(v);
            } else if (col[v] == col[u]) {       // 同一条边两端同色 → 存在奇环
                return false;
            }
        }
    }
    return true;
}

int main() {
    int n, m;
    scanf("%d %d", &n, &m);
    for (int i = 1; i <= m; ++i) {
        int u, v; scanf("%d %d", &u, &v);
        addEdge(u, v); addEdge(v, u);            // 无向边，存两份
    }

    memset(col, -1, sizeof col);                 // ★ 必须先置 -1
    for (int i = 1; i <= n; ++i) {               // 图可能不连通，每块各开一次
        if (col[i] != -1) continue;
        if (!paint(i)) { printf("No\n"); return 0; }
    }
    printf("Yes\n");
    return 0;
}''', "染色判定完整代码（输入 n、m 与 m 条无向边，输出 Yes / No）"))

