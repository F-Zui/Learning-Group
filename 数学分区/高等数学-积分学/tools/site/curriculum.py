def all_sections():
    for ch in CHAPTERS:
        for sid, title, core, diff in ch["sections"]:
            yield ch, sid, title, core, diff


def section_file(sid):
    return "sections/" + sid.replace(".", "-") + ".html"


def find(sid):
    for ch, s, title, core, diff in all_sections():
        if s == sid:
            return ch, title, core, diff
    raise KeyError(sid)
