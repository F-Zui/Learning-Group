def group_of(lid):
    for a, b, name in GROUPS:
        if a <= lid <= b:
            return name
    return "其他"


def all_lessons():
    out = []
    for (lid, title, level, star, minutes, tags, kind) in RAW:
        fname = "%02d.html" % lid
        out.append(dict(id=lid, title=title, level=level, star=star,
                        minutes=minutes, tags=tags, kind=kind,
                        group=group_of(lid), file=fname))
    return out


def meta(lid):
    for x in all_lessons():
        if x["id"] == lid:
            return x
    raise KeyError(lid)
