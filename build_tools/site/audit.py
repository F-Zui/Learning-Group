PREFIX_OK = ("P", "B", "T", "U", "CF", "AT", "SP")


def code_blocks(lesson):
    out = []
    for s in lesson.get("sections", []):
        if s.get("kind") == "code":
            out.append(s["code"])
        if s.get("kind") == "idea":
            for b in s.get("blocks", []):
                if isinstance(b, dict) and b.get("kind") == "code":
                    out.append(b["code"])
        if s.get("kind") == "func" and s.get("example"):
            out.append(s["example"])
    ch = lesson.get("challenge")
    if ch and ch.get("code"):
        out.append(ch["code"])
    for ch in lesson.get("challenges", []) or []:
        if ch.get("code"):
            out.append(ch["code"])
    for p in lesson.get("problems", []) or []:
        if p.get("code"):
            out.append(p["code"])
    return out


def main():
    metas = {m["id"]: m for m in curriculum.all_lessons()}
    issues = []
    total_code = 0
    for lid in sorted(metas):
        path = os.path.join(HERE, "lessons", "l%02d.py" % lid)
        if not os.path.exists(path):
            issues.append((lid, "缺少文件", path))
            continue
        mod = importlib.import_module("lessons.l%02d" % lid)
        items = getattr(mod, "LESSONS", [])
        if not items:
            issues.append((lid, "LESSONS 为空", ""))
            continue
        L = items[0]
        if int(L.get("id", -1)) != lid:
            issues.append((lid, "课号不符: %s" % L.get("id"), ""))
        if L.get("kind") not in (None, metas[lid]["kind"]):
            pass
        codes = code_blocks(L)
        total_code += len(codes)
        # 结构检查
        blocks = L.get("sections", [])
        def _flat(bs):
            out = []
            for b in bs:
                if isinstance(b, dict):
                    out.append(b.get("kind"))
                    if b.get("blocks"):
                        out.extend(_flat(b["blocks"]))
            return out
        kinds = _flat(blocks)
        if metas[lid]["kind"] == "lesson":
            if "example" not in kinds:
                issues.append((lid, "缺少例题 example", ""))
            if "idea" not in kinds:
                issues.append((lid, "缺少思路 idea", ""))
            if "code" not in kinds:
                issues.append((lid, "缺少完整代码 code", ""))
            if "explain" not in kinds:
                issues.append((lid, "缺少逐行拆解 explain", ""))
            if not L.get("math"):
                issues.append((lid, "缺少数学补给", ""))
            if len(L.get("think") or []) < 4:
                issues.append((lid, "think 少于 4 条", str(len(L.get("think") or []))))
            if not L.get("challenge"):
                issues.append((lid, "缺少挑战题", ""))
        else:
            if len(L.get("challenges") or []) < 4:
                issues.append((lid, "回顾/模拟赛题目不足 4", str(len(L.get("challenges") or []))))
        # 挑战题完整性
        chs = ([L["challenge"]] if L.get("challenge") else []) + list(L.get("challenges") or [])
        for ch in chs:
            for k in ("name", "code", "hint", "idea", "pitfalls"):
                if not ch.get(k):
                    issues.append((lid, "挑战题缺字段 %s (%s)" % (k, ch.get("name", "?"))[:40], ""))
            pid = str(ch.get("id", ""))
            if pid and not pid.startswith(PREFIX_OK):
                issues.append((lid, "题号格式可疑 %s" % pid, ""))
        # 代码块合理性
        for c in codes:
            if not c.strip():
                issues.append((lid, "空代码块", ""))
            if "..." in c and c.count("...") > 1:
                pass
        # 禁用词
        blob = render_str(L)
        for w in BAD_PHRASES:
            if w in blob:
                issues.append((lid, "出现比喻词「%s」" % w, ""))
        # 长度
        if len(blob) < 2500:
            issues.append((lid, "正文偏短 %d 字" % len(blob), ""))

    print("检查了 %d 节，代码块 %d 个，问题 %d 条" % (len(metas), total_code, len(issues)))
    for it in issues:
        print("  [%02d] %s %s" % it)


def render_str(lesson):
    """粗略统计正文长度（所有字符串）。"""
    buf = []

    def walk(o):
        if isinstance(o, str):
            buf.append(o)
        elif isinstance(o, dict):
            for v in o.values():
                walk(v)
        elif isinstance(o, (list, tuple)):
            for v in o:
                walk(v)

    walk(lesson.get("sections"))
    walk(lesson.get("math"))
    walk(lesson.get("think"))
    walk(lesson.get("challenge"))
    walk(lesson.get("challenges"))
    return "".join(buf)


