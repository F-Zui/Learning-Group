    P("设 a₁ ≤ a₂ ≤ … ≤ a_n，b₁ ≤ b₂ ≤ … ≤ b_n，σ 是 1..n 的任意排列。排序不等式说："),
    P("Σ a_i · b_{n+1−i} ≤ Σ a_i · b_{σ(i)} ≤ Σ a_i · b_i。"
      "左边是“逆序和”（大配小），最小；右边是“同序和”（大配大），最大。"),
    P("<b>证明只用一次相邻交换。</b>取两个位置，现在配的是 (a_j, b_k) 与 (a_k, b_j)，其中 j &lt; k。"
      "交换成 (a_j, b_j)、(a_k, b_k) 后，两者之差 = (a_j b_j + a_k b_k) − (a_j b_k + a_k b_j)"
      " = (a_k − a_j)(b_k − b_j) ≥ 0。"
      "所以“小 a 配大 b”的组合一旦存在，交换成同序一定不会变小——反过来读，逆序和最小。"),
    P("回看接水问题：总等待 = Σ T_i × (n − i)。系数 (n−1, n−2, …, 0) 是一列已经降序排好的数，T 是另一列。"
      "要让乘积和最小，就必须让两列的排序方向相反：T 升序 ↔ 系数降序。这就是“按 T 升序排队”的全部数学。"),
