SEC.append(C(r'''#include <bits/stdc++.h>
using namespace std;

const int N = 1005;
int n;
struct Node {
    int t;      // 接水用时
    int id;     // 原始编号：排序会打乱位置，编号必须跟着走
} a[N];

// 贪心策略：接水时间短的先上
bool cmp(const Node &x, const Node &y) {
    if (x.t != y.t) return x.t < y.t;   // 主键：时间升序
    return x.id < y.id;                 // 次键：时间相同，编号小的在前
}

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    cin >> n;
    for (int i = 1; i <= n; ++i) {
        cin >> a[i].t;
        a[i].id = i;                    // 记住它原本是第几个人
    }
    sort(a + 1, a + n + 1, cmp);        // O(n log n)，n = 1000 时约 1 万次比较

    long long sum = 0;                  // 总等待时间可达 5*10^11，int 装不下
    for (int i = 1; i <= n; ++i) {
        sum += 1LL * a[i].t * (n - i);  // 第 i 位的人被后面 n-i 人各等一次
        if (i > 1) cout << ' ';         // 分隔符：第一个数前面不打空格
        cout << a[i].id;
    }
    cout << '\n';
    cout << fixed << setprecision(2) << 1.0 * sum / n << '\n';
    return 0;
}''', "完整可编译代码（C++17）"))

