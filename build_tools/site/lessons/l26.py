SEC.append(C(r'''#include <bits/stdc++.h>
using namespace std;

int n, m, g[15][15];
int best[15][15];                    // best[x][y]：到达 (x,y) 时能保留的最大血量，-1 表示没到过
int dx[4] = {-1, 1, 0, 0};
int dy[4] = {0, 0, -1, 1};

struct State { int x, y, hp, step; };

int main() {
    cin >> n >> m;
    int sx = 0, sy = 0;
    for (int i = 1; i <= n; ++i)
        for (int j = 1; j <= m; ++j) {
            char c; cin >> c;
            g[i][j] = c - '0';
            if (g[i][j] == 2) { sx = i; sy = j; }
            best[i][j] = -1;
        }

    queue<State> q;
    q.push({sx, sy, 6, 0});
    best[sx][sy] = 6;                // ★ 入队的同一时刻标记，别等出队

    while (!q.empty()) {
        State u = q.front(); q.pop();
        for (int k = 0; k < 4; ++k) {
            int nx = u.x + dx[k], ny = u.y + dy[k];
            if (nx < 1 || nx > n || ny < 1 || ny > m) continue;   // 先判越界
            if (g[nx][ny] == 0) continue;                          // 障碍
            int hp = u.hp - 1;                                     // 走一格的代价
            if (hp <= 0) continue;                                 // 死在半路，这一步不合法
            if (g[nx][ny] == 4) hp = 6;                            // 鼠标：瞬间补满
            if (g[nx][ny] == 3) { cout << u.step + 1 << "\n"; return 0; }  // 第一次到家即最短
            if (hp <= best[nx][ny]) continue;                      // 血不更多 → 被别的状态压制
            best[nx][ny] = hp;
            q.push({nx, ny, hp, u.step + 1});
        }
    }
    cout << -1 << "\n";              // 队列空了还没到家
    return 0;
}''', "完整代码"))

