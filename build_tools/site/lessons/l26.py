SEC.append(WARN("BFS 的 7 种典型错法（含症状）", [
    "<b>WA：除源点外全是 −1</b>。—— dis 没置 −1（全局数组默认 0），判重条件 <code>dis != -1</code> "
    "对所有格子都成立，第一次扩展就全被跳过。",
    "<b>WA：答案偏大</b>。—— 在出队时才标记。同一个格子被多个前驱各 push 一次，队列膨胀；"
    "如果 dis 又在 push 时被无条件覆盖，后写入的较大距离会盖掉先写入的最小值。标记要和 push 同时发生。",
    "<b>RE（内存吃光）或 TLE 死循环</b>。—— 删掉判重那一行。棋盘有环，A→B→A 会无限入队，"
    "几秒内队列吃掉几十 MB 然后 RE。",
    "<b>RE：数组越界</b>。—— 棋盘是 1-based 却写成 <code>nx &lt; 0</code>，或者根本不判越界。"
    "数组开 405 时 n = 400 读到 dis[401][*] 不会立刻崩，症状是随机 WA。",
    "<b>WA：大片格子变成 −1</b>。—— 方向数组少写了几组，或者 dx/dy 的正负号没配对（<code>dx[k]</code> 与 <code>dy[k]</code> 必须同属一个方向）。",
    "<b>TLE：多源题写成了单源循环</b>。—— 对每个源点各跑一次 BFS，复杂度 k × nm。多源 BFS 只跑一次。",
    "<b>WA：每个格子都比正确答案少 1，源点变成 −1</b>。—— push 了源点却忘了写 "
    "<code>dis[sx][sy] = 0</code>，于是第一层算出的是 −1 + 1 = 0，整张表跟着错位。",
]))

