SEC.append(C(r'''#include <bits/stdc++.h>
using namespace std;

const int MAXN = 5000005;      // 题目上限 5×10⁶，再多留几个位给 d[n+1]
int a[MAXN], d[MAXN];          // a 存初始成绩，d 存差分

int main() {
    ios::sync_with_stdio(false);   // 5×10⁶ 个整数，必须提速
    cin.tie(nullptr);

    int n, p;
    cin >> n >> p;
    for (int i = 1; i <= n; ++i) cin >> a[i];

    for (int i = 1; i <= n; ++i)
        d[i] = a[i] - a[i - 1];    // a[0] 是全局数组，默认 0，所以 d[1] = a[1] 自动成立

    while (p--) {
        int x, y, z;
        cin >> x >> y >> z;
        d[x]     += z;             // 从 x 开始，每个还原值都比原来多 z
        d[y + 1] -= z;             // 从 y+1 开始把这层 z 扣掉，恢复原样
    }

    int cur = 0, mn = INT_MAX;
    for (int i = 1; i <= n; ++i) {
        cur += d[i];               // 前缀和还原：cur 就是最终的 a[i]
        if (cur < mn) mn = cur;    // 边还原边统计最低分，省下第三个数组
    }
    cout << mn << "\n";
    return 0;
}''', "完整代码"))

