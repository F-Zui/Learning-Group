# ---------------------------------------------------------------- 线性筛
SEC.append(P("埃氏筛有个小浪费：一个合数会被它的每个质因子各划一次，比如 30 会被 2、3、5 各划一遍。"
             "线性筛把它修掉——让每个合数<b>只被它的最小质因子划一次</b>，代价是多用一个数组 primes 存已找到的质数，"
             "顺手还能免费得到每个数的最小质因子表 lpf。"))

SEC.append(C(r'''const int MAXN = 1000000 + 5;
vector<int> primes;          // 已找到的质数，从小到大
int lpf[MAXN];               // lpf[k]：k 的最小质因子
bool isp[MAXN];              // 是否是质数

void eulerSieve(int n) {
    primes.clear();                          // 多测：上一轮攒下的质数必须清掉
    fill(isp, isp + n + 1, true);
    isp[0] = isp[1] = false;

    for (int i = 2; i <= n; ++i) {
        if (isp[i]) {
            primes.push_back(i);
            lpf[i] = i;                        // 质数的最小质因子是它自己
        }
        for (int p : primes) {
            if ((long long)p * i > n) break;   // 越界，后面的 p 只会更大
            isp[p * i] = false;
            lpf[p * i] = p;                    // p 是 p*i 的最小质因子
            if (i % p == 0) break;             // ★ 关键的一句，见下表
        }
    }
}''', "线性筛（欧拉筛）"))

