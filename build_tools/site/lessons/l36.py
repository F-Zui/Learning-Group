SEC.append(C(r'''// 统计 [L, R] 内的质数个数，要求 L ≥ 1，R ≤ 10^12，R - L ≤ 10^6
long long countPrimes(long long L, long long R) {
    int lim = (int)sqrt((long double)R) + 1;        // 只需 √R 以内的质数
    vector<char> small(lim + 1, 1);
    small[0] = small[1] = 0;
    for (int i = 2; i <= lim / i; ++i)
        if (small[i])
            for (int j = i * i; j <= lim; j += i) small[j] = 0;

    vector<char> seg(R - L + 1, 1);                 // seg[k] 对应数字 L + k
    if (L == 1) seg[0] = 0;                         // 1 不是质数

    for (int i = 2; i <= lim; ++i) {
        if (!small[i]) continue;
        long long p = i;
        // 从 p*p 与 “不小于 L 的最小 p 的倍数” 中取较大者
        long long start = max(p * p, (L + p - 1) / p * p);
        for (long long j = start; j <= R; j += p) seg[j - L] = 0;
    }

    long long cnt = 0;
    for (long long k = L; k <= R; ++k) cnt += seg[k - L];
    return cnt;
}''', "区间筛：把 [L, R] 平移成 [0, R−L]"))

