SEC.append(C(r'''#include <bits/stdc++.h>
using namespace std;

int n;
double x[16], y[16];
double d[16][16];                  // d[i][j]：编号 i 与 j 的直线距离
double f[1 << 15][15];             // f[S][i]：已吃集合 S、最后一口在 i 的最小路程

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    cin >> n;
    x[0] = y[0] = 0;                               // 0 号点就是原点，当作起点
    for (int i = 1; i <= n; ++i) cin >> x[i] >> y[i];

    for (int i = 0; i <= n; ++i)                   // 两两距离只跟坐标有关，先算成表
        for (int j = 0; j <= n; ++j) {
            double dx = x[i] - x[j], dy = y[i] - y[j];
            d[i][j] = sqrt(dx * dx + dy * dy);     // 开方只做 (n+1)² 次，别放进转移里
        }

    int full = (1 << n) - 1;                       // 全部吃完的集合
    for (int S = 0; S <= full; ++S)
        for (int i = 0; i < n; ++i) f[S][i] = 1e18;   // 求最小，INF 要足够大

    for (int i = 0; i < n; ++i)
        f[1 << i][i] = d[0][i + 1];                // 第一口：从原点直接过去（注意 +1 的下标错位）

    for (int S = 1; S <= full; ++S)                // S 递增天然就是拓扑序
        for (int i = 0; i < n; ++i) {
            if (!(S >> i & 1)) continue;           // i 不在集合里，这个状态无意义
            for (int j = 0; j < n; ++j) {
                if (S >> j & 1) continue;          // j 已经吃过，不能重复吃
                int T = S | (1 << j);              // 新集合：把 j 加进去
                double nd = f[S][i] + d[i + 1][j + 1];
                if (nd < f[T][j]) f[T][j] = nd;    // 松弛
            }
        }

    double ans = 1e18;
    for (int i = 0; i < n; ++i) ans = min(ans, f[full][i]);
    printf("%.2f\n", ans);
    return 0;
}''', "完整可编译代码（C++17）"))

