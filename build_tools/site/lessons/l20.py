SEC.append(FN(
    "pre 与 minpre（前缀和 + 历史最小值）",
    "pre[i] = pre[i-1] + a[i];\nans = max(ans, pre[i] - minpre);   // minpre = min(pre[0..i-1])\nminpre = min(minpre, pre[i]);",
    [("pre[i]", "前 i 个数的和，是<b>累计量</b>而不是原数组。区间和靠两个前缀相减得到。"),
     ("pre[r] - pre[l-1]", "区间 [l, r] 的和。一次减法顶替一次长度为 len 的循环。"),
     ("minpre", "已经扫过的所有前缀里的最小值（含 pre[0] = 0）。固定右端点 r 时，减数越小答案越大。"),
     ("更新顺序", "先用旧的 minpre 算答案，再把 pre[i] 并进 minpre。<b>顺序反了就等于允许空区间。</b>"),
     ("ans 初值", "必须取负无穷（LLONG_MIN）。子段非空，全负数时答案是“最大的那个负数”，不是 0。"),
     ("量级", "n = 2×10⁵、|a| = 10⁴ 时 |pre| 可达 2×10⁹，已经贴住 int 上限，用 long long。")],
    example=r'''long long pre = 0, minpre = 0, ans = LLONG_MIN;   // minpre 的初值 0 就是 pre[0]
for (int i = 1; i <= n; ++i) {
    pre += a[i];                    // pre 此刻等于 pre[i]
    ans = max(ans, pre - minpre);   // ① 先算答案，保证区间非空
    minpre = min(minpre, pre);      // ② 再把 pre[i] 并进历史最小值
}
// a = {2, -4, 3, -1, 2, -4, 3} → ans = 4，来自 3 + (-1) + 2''',
    notes=["把 ①② 换序：先 minpre = min(minpre, pre) 再算答案，减数可能取到 pre[i] 本身，等于允许空段。"
           "症状是<b>全负数数据输出 0</b>。",
           "存了 pre 数组却每次从 1 到 r 找最小值，复杂度退回 O(n²)——minpre 的意义就是“顺手记下过去的最好值”。"],
    brief="区间和 = 两个前缀相减；最大值 = 当前前缀 − 历史最小前缀"))

SEC.append(FN(
    "d 数组（差分）与“正部之和”",
    "d[i] = a[i] - a[i-1];\nans += max(0, a[i] - a[i-1]);   // 只累加上升量",
    [("d[i]", "相邻两项的变化量。区间加 z 只需要 <code>d[l] += z</code>、<code>d[r+1] -= z</code> 两次单点修改。"),
     ("还原", "对 d 求一遍前缀和才得到真实值。<b>d 本身不是答案</b>，它只是记账。"),
     ("正部之和", "把一段序列“削平”（每次让一个连续区间减 1）的最少次数 = d[1] + Σ max(0, d[i] − d[i−1])，"
                "也就是所有上升量之和。"),
     ("为什么", "每次操作最多消掉一个单位的高度差，所以“上升量之和”是下界；"
              "按“每逢上升就新开几次操作”的策略恰好取到这个下界，于是它也是上界。"),
     ("数组大小", "要写 d[r+1]，而 r 可以等于 n，所以开 n+2。"),
     ("流式写法", "只求和时不用存数组：读一个数、与上一个比较，O(1) 空间。")],
    example=r'''// 铺设道路：n 段深度 d[i]，每次把一段连续区间每段减 1，求最少次数
int prev = 0;   long long ans = 0;      // prev 相当于 d[0] = 0
for (int i = 1; i <= n; ++i) {
    int d; cin >> d;
    if (d > prev) ans += d - prev;      // 只累加“上升”的部分
    prev = d;
}
// 4 3 2 5 3 5 → 4 + 3 + 2 = 9''',
    notes=["算成 Σ|d[i] − d[i−1]| 会把下降量也算进去，答案偏大。",
           "忘掉 prev 的初值 0，第一段就少了 d[1] 次操作。"],
    brief="区间加只改两个端点；削平次数 = 上升量之和"))

