SEC.append(C(r'''#include <bits/stdc++.h>
using namespace std;

const int N = 100005;
int n, m;
vector<vector<int>> g;            // g[u] = u 引用的所有文献
bool vis[N];                      // 访问标记：两个序列共用，用前都要清

void dfs(int u) {
    vis[u] = true;
    cout << u << " ";             // 先序：一进点就输出，这就是"DFS 序列"
    for (int v : g[u])            // g[u] 已升序，天然满足"先看编号小的"
        if (!vis[v]) dfs(v);      // 有环时必须判重，否则无限递归
}

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    cin >> n >> m;
    g.resize(n + 1);              // n+1 条空表，下标 1..n 可用
    for (int i = 0; i < m; ++i) {
        int x, y;
        cin >> x >> y;
        g[x].push_back(y);        // 有向边 X→Y，只加一个方向
    }
    for (int u = 1; u <= n; ++u)  // 每个邻接表单独升序
        sort(g[u].begin(), g[u].end());

    dfs(1);                       // 从 1 号文章出发
    cout << "\n";

    memset(vis, 0, sizeof(vis));  // ★ 第二轮必须清空
    queue<int> q;
    q.push(1);
    vis[1] = true;                // 入队即标记，不能等出队
    while (!q.empty()) {
        int u = q.front();
        q.pop();                  // front 取值、pop 删除，两句不能合并
        cout << u << " ";
        for (int v : g[u])
            if (!vis[v]) {        // 判重同时保证"每个点只进队一次"
                vis[v] = true;
                q.push(v);
            }
    }
    cout << "\n";
    return 0;
}''', "完整代码（C++17）"))

