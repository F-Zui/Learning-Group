SEC.append(C(r'''#include <bits/stdc++.h>
using namespace std;

const int NL = 505;                     // 左侧点数上限
const int NR = 505;                     // 右侧点数上限
const int ME = 100005;                  // 边数上限（题给 5×10^4，留一倍余量）

int head[NL], nxt[ME], to[ME], ecnt;
int match[NR];                          // match[v]：右侧点 v 配给的左侧点，0 表示空
bool vis[NR];                           // 本轮 dfs 中右侧点是否试过

void addEdge(int u, int v) {
    to[++ecnt] = v; nxt[ecnt] = head[u]; head[u] = ecnt;
}

bool dfs(int u) {
    for (int e = head[u]; e; e = nxt[e]) {
        int v = to[e];
        if (vis[v]) continue;                    // 本轮试过，跳过（防绕圈）
        vis[v] = true;                           // 先标记，成功失败都不再试
        if (match[v] == 0 || dfs(match[v])) {    // v 空着，或原配能另找出路
            match[v] = u;                        // 接手 v
            return true;
        }
    }
    return false;                                // 所有候选都被堵死
}

int main() {
    int n, m, e;
    scanf("%d %d %d", &n, &m, &e);
    for (int i = 1; i <= e; ++i) {
        int u, v; scanf("%d %d", &u, &v);
        addEdge(u, v);                           // 只存左侧 -> 右侧的单向边
    }

    int ans = 0;
    for (int u = 1; u <= n; ++u) {               // 每个左侧点各发起一次尝试
        memset(vis, 0, sizeof vis);              // ★ 新一轮必须重新清空
        if (dfs(u)) ++ans;                       // 找到增广路，匹配数恰好 +1
    }
    printf("%d\n", ans);
    return 0;
}''', "完整代码"))

