SEC.append(C(r'''int l = 1, r = n;
bool ok = false;
while (l < r) {
    int s = a[l] + a[r];
    if (s == x) { ok = true; break; }
    else if (s < x) ++l;      // a[l] 配谁都太小，这一整排候选全部作废
    else            --r;      // a[r] 配谁都太大，这一整列候选全部作废
}''', "两端收缩"))

SEC.append(P("为什么不会漏解？设当前 a[l] + a[r] &lt; x。对任意 j ≤ r，因为数组升序，a[l] + a[j] ≤ a[l] + a[r] &lt; x，"
             "所以 a[l] 和任何右端点都凑不出 x——l 可以永久丢弃。"
             "反过来 a[l] + a[r] &gt; x 时，a[r] 配任何左端点都太大，r 可以永久丢弃。每一次移动都丢掉一整排，总共丢 n 次就结束。"))

