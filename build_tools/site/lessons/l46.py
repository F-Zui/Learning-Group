SEC.append(C(r'''#include <bits/stdc++.h>
using namespace std;

const int N = 500005;
int n, a[N], t[N];                    // t 的下标是"值"，不是"位置"

int lowbit(int x) { return x & -x; }

void add(int i, int v) {
    for (; i <= n; i += lowbit(i)) t[i] += v;
}

int sum(int i) {
    int s = 0;
    for (; i > 0; i -= lowbit(i)) s += t[i];
    return s;
}

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    cin >> n;
    for (int i = 1; i <= n; ++i) cin >> a[i];   // 保证 1 <= a[i] <= n

    long long ans = 0;
    for (int i = 1; i <= n; ++i) {
        ans += (i - 1) - sum(a[i]);   // 前面 i-1 个里，≤ a[i] 的有 sum(a[i]) 个
        add(a[i], 1);                 // 再把 a[i] 记进去：这个值多出现了一次
    }
    cout << ans << "\n";
    return 0;
}''', "逆序对（值域 ≤ n 的版本）"))

