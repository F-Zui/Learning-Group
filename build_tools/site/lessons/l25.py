SEC.append(C(r'''#include <bits/stdc++.h>
using namespace std;

int n, target, a[15], coef[15];     // coef[i] = C(n-1, i)
bool used[15];

// step：正在填第几个位置；s：已填部分的加权和
bool dfs(int step, int s) {
    if (s > target) return false;              // 剪枝：系数全正，s 只会越来越大
    if (step == n) return s == target;         // 出口：n 个位置都填好了
    for (int v = 1; v <= n; ++v) {
        if (used[v]) continue;                 // 排列：每个数只能用一次
        used[v] = true;
        a[step] = v;
        if (dfs(step + 1, s + v * coef[step])) return true;   // 找到就一路返回
        used[v] = false;                       // 回溯
    }
    return false;
}

int main() {
    cin >> n >> target;

    coef[0] = 1;                               // 杨辉三角第 n 行：C(n-1, i) = C(n-1, i-1) * (n-i) / i
    for (int i = 1; i < n; ++i) coef[i] = coef[i - 1] * (n - i) / i;

    if (dfs(0, 0)) {                           // 有解才输出
        for (int i = 0; i < n; ++i) cout << a[i] << (i == n - 1 ? '\n' : ' ');
    }
    return 0;
}''', "完整代码 · 排列枚举 + 加权和剪枝"))

