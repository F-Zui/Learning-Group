     ("分支", "<code>for</code> 枚举这一步的所有选择，每个选择先「改状态」，再递归，再「还原状态」。"),
     ("回溯", "递归返回后把状态改回去。漏了这一步，后面的分支会看到被污染的状态，答案偏少且难查。"),
