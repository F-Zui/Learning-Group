SEC.append(C(r'''#include <bits/stdc++.h>
using namespace std;

int m, n, sx, sy, tx, ty;
int g[20][20];              // 1 可走，0 不可走
int vis[20][20];            // 是否在当前路径上
int px[500], py[500];       // 当前路径，最多 m*n 个点
bool found = false;
int dx[4] = {0, -1, 0, 1};  // 左、上、右、下：题目规定的扩展顺序
int dy[4] = {-1, 0, 1, 0};

void dfs(int x, int y, int d) {          // d：路径上已有 d 个点，当前点是第 d 个
    if (x == tx && y == ty) {            // 到终点：打印这条路径
        for (int i = 0; i < d; ++i) {
            if (i) printf("->");
            printf("(%d,%d)", px[i], py[i]);
        }
        printf("\n");
        found = true;
        return;                          // 到终点必须停，否则同一条路径会被重复计数
    }
    for (int k = 0; k < 4; ++k) {
        int nx = x + dx[k], ny = y + dy[k];
        if (nx < 1 || nx > m || ny < 1 || ny > n) continue;   // 先判越界
        if (!g[nx][ny] || vis[nx][ny]) continue;              // 墙，或本路径已走过
        vis[nx][ny] = 1;                 // ① 占位
        px[d] = nx; py[d] = ny;          // 记进路径
        dfs(nx, ny, d + 1);              // ② 递进
        vis[nx][ny] = 0;                 // ③ 撤销：别的路径还要用这一格
    }
}

int main() {
    cin >> m >> n;
    for (int i = 1; i <= m; ++i)
        for (int j = 1; j <= n; ++j) cin >> g[i][j];
    cin >> sx >> sy >> tx >> ty;

    if (sx == tx && sy == ty) {          // 起点即终点：题目约定输出 -1
        cout << -1 << "\n";
        return 0;
    }
    px[0] = sx; py[0] = sy;
    vis[sx][sy] = 1;                     // 起点算走过，防止路径绕回起点
    dfs(sx, sy, 1);
    if (!found) cout << -1 << "\n";      // 一条路都没有
    return 0;
}''', "完整可编译代码（C++17）"))

