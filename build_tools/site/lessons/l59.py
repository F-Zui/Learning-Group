SEC.append(C(r'''#include <bits/stdc++.h>
using namespace std;

const int N = 100005;
const double EPS = 1e-9;

struct Vec {
    double x, y;
    Vec operator-(const Vec& b) const { return {x - b.x, y - b.y}; }
    bool operator<(const Vec& b) const { return x != b.x ? x < b.x : y < b.y; }
};

int n;
Vec p[N], h[N];

double cross(Vec a, Vec b) { return a.x * b.y - a.y * b.x; }
double dot(Vec a, Vec b)   { return a.x * b.x + a.y * b.y; }
double len(Vec a)          { return sqrt(dot(a, a)); }
int sgn(double x)          { return x > EPS ? 1 : (x < -EPS ? -1 : 0); }

int main() {
    scanf("%d", &n);
    for (int i = 0; i < n; ++i) scanf("%lf%lf", &p[i].x, &p[i].y);

    sort(p, p + n);                        // 凸包第一步：按 x 再按 y

    int m = 0;
    for (int i = 0; i < n; ++i) {          // 下链：从左到右，只留左转
        while (m >= 2 && sgn(cross(h[m - 1] - h[m - 2], p[i] - h[m - 1])) <= 0) --m;
        h[m++] = p[i];
    }
    int k = m;                             // 下链的点数，上链不能把它们弹掉
    for (int i = n - 2; i >= 0; --i) {     // 上链：从右到左
        while (m > k && sgn(cross(h[m - 1] - h[m - 2], p[i] - h[m - 1])) <= 0) --m;
        h[m++] = p[i];
    }
    --m;                                   // 末尾与起点重复，去掉

    double ans = 0;
    for (int i = 0; i < m; ++i)
        ans += len(h[(i + 1) % m] - h[i]); // 首尾相连，最后一条边要绕回去
    printf("%.2f\n", ans);
    return 0;
}''', "完整可编译代码（C++17）"))

