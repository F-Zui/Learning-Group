SEC.append(C(r'''#include <bits/stdc++.h>
using namespace std;

int main() {
    int k;
    cin >> k;                  // 1 <= k <= 15

    double s = 0.0;            // 累加器：部分和，必须是浮点
    int n = 0;                 // 已经加了多少项

    while (s <= k) {           // 还没超过 k，就再补一项
        ++n;                   // 先定下“这一轮加第 n 项”，顺序不能反
        s += 1.0 / n;          // 写 1.0 才是浮点除法；写 1 / n 会永远停不下来
    }

    cout << n << "\n";         // 此时 s 第一次超过 k，n 就是最小解
    return 0;
}''', "完整代码"))

