SEC.append(IDEA("为什么要每次取最小的两堆", [
    P("先看清代价的结构：一堆果子被合并 d 次，它的数量就被算进总代价 d 次。"
      "所以<b>重的应该少被合并（离根浅），轻的应该多被合并（离根深）</b>。"
      "把每次合并画成一棵二叉树，总代价 = Σ a_i × 深度_i。"),
    P("交换论证：最优树里最轻的两堆一定在最深层且互为兄弟。若最轻的叶子不在最深层，"
      "把它与最深的叶子交换，小权值下移、大权值上移，WPL 只会变小，与最优性矛盾。"
      "所以先合并最轻的两堆不损失最优性，剩下问题同构，归纳即可。"),
    P("实现上有个关键点：<b>合并出的新堆必须重新参与比较</b>。排一次序就固定的做法是错的"
      "（1、2、9 合并出 3 之后，3 比 9 小，下一轮该先碰它）。集合动态变化，所以用堆："
      "每次 top 两次、pop 两次、push 一次，n − 1 轮，总 O(n log n)。"
      "这是本课程第一次出现“贪心 + 数据结构”。"),
]))

SEC.append(C(r'''#include <bits/stdc++.h>
using namespace std;

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int n;
    cin >> n;
    // 三个模板参数：元素类型、底层容器、比较器。greater 表示小的优先 -> 小根堆
    priority_queue<int, vector<int>, greater<int>> q;
    for (int i = 0; i < n; ++i) {
        int w;
        cin >> w;
        q.push(w);
    }

    long long cost = 0;                 // 本题保证答案 < 2^31，但用 long long 不亏
    while (q.size() > 1) {              // 合并 n-1 次，剩 1 堆时结束
        int x = q.top(); q.pop();       // 当前最轻的两堆
        int y = q.top(); q.pop();
        cost += x + y;                  // 这次合并消耗的体力
        q.push(x + y);                  // 新堆放回集合，参与后面的合并
    }
    cout << cost << '\n';
    return 0;
}''', "完整可编译代码（C++17）"))

SEC.append(EXPLAIN("逐行拆解", [
    ("priority_queue<int, vector<int>, greater<int>> q;",
     "小根堆：top() 始终是最轻的一堆。用默认大根堆会先合并最大的两堆，答案偏大。"),
    ("while (q.size() > 1)",
     "合并 n − 1 次，剩 1 堆时停。写成 while (!q.empty()) 会在最后一轮第二次 pop 时取空堆。"),
    ("int x = q.top(); q.pop(); int y = q.top(); q.pop();",
     "连续取两个最小值。必须先 top 再 pop，两句不能合并（pop 没有返回值）。"),
    ("cost += x + y;",
     "这次合并的体力消耗就是两堆之和，也是这棵子树的根权值。"),
    ("q.push(x + y);",
     "新堆必须放回去。漏了这一行，下一轮会比较到已经不存在的旧值，答案偏离。"),
]))

