SEC.append(C(r'''#include <bits/stdc++.h>
using namespace std;

const int N = 1000005;
int n;
struct Seg { int l, r; } a[N];

// 唯一的贪心决策：按右端点升序
bool cmp(const Seg &x, const Seg &y) {
    if (x.r != y.r) return x.r < y.r;   // 主键：越早结束越优先
    return x.l < y.l;                   // 次键：保证严格弱序
}

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    cin >> n;
    for (int i = 1; i <= n; ++i) cin >> a[i].l >> a[i].r;
    sort(a + 1, a + n + 1, cmp);        // O(n log n)，n = 10^6 也能过

    int ans = 0, last = 0;              // last = 上一场的结束时刻；时刻都 >= 0，初值 0 安全
    for (int i = 1; i <= n; ++i) {
        if (a[i].l >= last) {           // 接得上（等号不能少：t 结束、t 开始是允许的）
            ++ans;
            last = a[i].r;              // 只有真的选了才更新，这是贪心的"落子"
        }
    }
    cout << ans << '\n';
    return 0;
}''', "完整可编译代码（C++17）"))

