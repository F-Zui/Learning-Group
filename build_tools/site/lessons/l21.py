SEC.append(C(r'''#include <bits/stdc++.h>
using namespace std;

int n, cnt = 0;
int a[15];                  // 正在拼的这 10 个质量，用 a[1..10]
int ans[9005][11];          // 全部方案：n = 20 时最多 8953 个

void dfs(int step, int sum) {
    // 可行性剪枝：剩下的 11-step 格，全填 1 都超了、或全填 3 都不够，整棵子树砍掉
    if (sum + (11 - step) > n) return;
    if (sum + 3 * (11 - step) < n) return;

    if (step == 11) {               // 10 格填满；能走到这里，和一定正好等于 n
        ++cnt;
        for (int i = 1; i <= 10; ++i) ans[cnt][i] = a[i];
        return;
    }
    for (int v = 1; v <= 3; ++v) {  // 从小到大：字典序靠的就是这个顺序
        a[step] = v;
        dfs(step + 1, sum + v);
    }
}

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    cin >> n;
    dfs(1, 0);                      // 从第 1 格开始填，当前和是 0

    cout << cnt << "\n";            // 第一行：方案总数
    for (int i = 1; i <= cnt; ++i)
        for (int j = 1; j <= 10; ++j)
            cout << ans[i][j] << (j == 10 ? '\n' : ' ');
    return 0;
}''', "完整可编译代码（C++17）"))

