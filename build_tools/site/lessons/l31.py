SEC.append(C(r'''#include <bits/stdc++.h>
using namespace std;

const int MAXN = 1005;         // n ≤ 1000，开 1005 让下标 1000 安全
int a[MAXN][MAXN];             // 原始数字三角形
int dp[MAXN][MAXN];            // dp[i][j]：从顶走到 (i,j) 的最大路径和

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int n;
    cin >> n;
    for (int i = 1; i <= n; ++i)
        for (int j = 1; j <= i; ++j)
            cin >> a[i][j];

    // ③ 边界：起点没有“上面”，它的路径和就是它自己
    dp[1][1] = a[1][1];

    // ② 转移：按行推进。第 i 行只依赖第 i-1 行，所以“按行的顺序”天然就是合法的计算顺序
    for (int i = 2; i <= n; ++i)
        for (int j = 1; j <= i; ++j) {
            if (j == 1)                       // 左边缘：没有左上格子，只能从正上方来
                dp[i][j] = a[i][j] + dp[i - 1][j];
            else if (j == i)                  // 右边缘：没有正上格子，只能从左上方来
                dp[i][j] = a[i][j] + dp[i - 1][j - 1];
            else                              // 中间：两个前驱取优
                dp[i][j] = a[i][j] + max(dp[i - 1][j - 1], dp[i - 1][j]);
        }

    // ④ 答案：底行最大值，不是 dp[n][n]
    int ans = dp[n][1];
    for (int j = 2; j <= n; ++j) ans = max(ans, dp[n][j]);

    cout << ans << "\n";
    return 0;
}''', "完整代码"))

